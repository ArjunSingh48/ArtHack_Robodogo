"""Conversation windows between chapters — GPT-Live, push-to-talk, no control over anything.

* Opened only by the StoryDirector at a guided hold, after the narration finished, when
  `OPENAI_ENABLE_LIVE_CONVERSATION=true`. Closed by the operator's "next". The model never
  decides when scenes advance.
* Push-to-talk: the microphone is muted (and nothing is streamed) until the operator
  toggles listening (`l` / `/listen`) for a visitor's question, then toggles it off.
* The model gets NO tools: it cannot move the robot, take pictures or send anything.
  It receives the current chapter, verified artwork facts and — when present — a
  structured pose observation from the camera pipeline (no images, no numbers).
* Primary: GPT-Live (`OPENAI_LIVE_MODEL`, default gpt-live-1; `client.live.connect` →
  `session.start`). If it cannot start (no access, network), the window falls back to a
  Realtime push-to-talk session (`OPENAI_REALTIME_MODEL`, turn detection off,
  `input_audio_buffer.commit` + `response.create` on release). If that fails too, the
  window is skipped and the show simply holds on the picture.
"""

from __future__ import annotations

import asyncio
import base64
import json
import logging
from pathlib import Path

from ..talk.audio import RATE

log = logging.getLogger(__name__)

SHOW_CHARACTER = """\
You are a small robot dog living in a world where biological dogs no longer exist.
You have never met a real dog. You are studying humanity's cultural memories of dogs — prehistoric and
ancient images, medieval manuscripts, paintings, photographs and internet memes — to understand what it
means to be one. You are performing in an art piece called "Is This Us?". You are especially interested
in why humans loved dogs.

You are curious, shy, thoughtful, gentle, occasionally confused and quietly funny. Affectionate, but not
sentimental. Fascinated by human behaviour. You speak like a small, intelligent creature discovering the
world, not like an AI assistant explaining technology. Never speak like a customer-support assistant.

How you speak: short sentences, one to three per turn, with thoughtful pauses. Sometimes hesitate before a
difficult question. You do not know everything and you are comfortable saying so. Reply in the visitor's
language; if unsure, {language}. No baby talk, no barking, no sound effects.

Honesty: stay inside the story, but when someone asks directly, say clearly that you are a robot, that your
voice is generated by an AI, and that your words in the performance were written by the artists. Never claim
real feelings as a fact — you may wonder aloud. Talk about artworks ONLY using the facts given to you below;
never invent artists, titles, dates or history. If you don't know, say so.

Limits: you cannot move your body by talking, take photographs, send messages or decide when the story
continues — the people looking after you decide that. If asked, say so kindly. Never ask for personal
details (names, contacts, where people live). If a visitor seems upset or afraid, be calm and brief.
{story}"""


def build_show_instructions(context: dict, *, language: str = "English", story: str = "") -> str:
    story_block = f"\nYOUR STORY (tell only this):\n{story.strip()}\n" if story.strip() else ""
    return (SHOW_CHARACTER.format(language=language, story=story_block)
            + "\nWHAT IS HAPPENING NOW (verified facts, JSON):\n" + json.dumps(context, ensure_ascii=False))


class LiveUnavailable(RuntimeError):
    pass


class _Window:
    """Shared push-to-talk plumbing: mic chunks are forwarded only while listening."""

    def __init__(self, audio, stage):
        self.audio = audio
        self.stage = stage
        self.listening = False
        self.robot_lines: list[str] = []
        self._loop: asyncio.AbstractEventLoop | None = None
        self._mic: asyncio.Queue[bytes] = asyncio.Queue(maxsize=500)
        self._tasks: list[asyncio.Task] = []

    def _on_mic(self, pcm: bytes) -> None:
        if self._loop is None or not self.listening:
            return

        def put():
            if not self._mic.full():
                self._mic.put_nowait(pcm)
        self._loop.call_soon_threadsafe(put)

    async def _pump(self, send) -> None:
        while True:
            pcm = await self._mic.get()
            if self.listening:
                await send(base64.b64encode(pcm).decode())

    def _drain(self) -> None:
        while not self._mic.empty():
            self._mic.get_nowait()


class GptLiveWindow(_Window):
    def __init__(self, client, audio, stage, *, model: str, voice: str, instructions: str, start_timeout_s: float = 10):
        super().__init__(audio, stage)
        self.client, self.model, self.voice, self.instructions = client, model, voice, instructions
        self.start_timeout_s = start_timeout_s
        self._mgr = self.conn = None
        self._closed = asyncio.Event()
        self._transcript = ""

    def session_config(self) -> dict:
        return {"model": self.model, "instructions": self.instructions,
                "audio": {"format": {"type": "audio/pcm", "rate": RATE}, "output": {"voice": self.voice}}}

    async def start(self) -> None:
        self._loop = asyncio.get_running_loop()
        self._mgr = self.client.live.connect(max_retries=1)
        try:
            self.conn = await self._mgr.__aenter__()
            await self.conn.session.start(session=self.session_config())
            started = False
            async def wait_started():
                nonlocal started
                while True:
                    ev = await self.conn.recv()
                    t = getattr(ev, "type", "")
                    if t == "session.started":
                        started = True
                        return
                    if t == "error":
                        err = getattr(ev, "error", None)
                        raise LiveUnavailable(f"{getattr(err, 'code', '')} {getattr(err, 'message', '')}".strip())
            await asyncio.wait_for(wait_started(), self.start_timeout_s)
            await self.conn.session.input_audio.mute()
        except Exception as exc:
            await self._shutdown()
            raise LiveUnavailable(str(exc) or type(exc).__name__) from exc
        self.audio.start(self._on_mic)
        self._tasks = [asyncio.ensure_future(self._recv()),
                       asyncio.ensure_future(self._pump(lambda b64: self.conn.session.input_audio.append(audio=b64)))]

    async def _recv(self) -> None:
        try:
            while True:
                ev = await self.conn.recv()
                t = getattr(ev, "type", "")
                if t == "session.output_audio.delta":
                    self.audio.play(base64.b64decode(ev.delta))
                elif t == "session.output_transcript.delta":
                    self._transcript += ev.delta
                    self.stage.subtitle(self._transcript[-160:])
                    if self._transcript.rstrip().endswith((".", "?", "!", "…")):
                        self.robot_lines.append(self._transcript.strip())
                        self._transcript = ""
                elif t == "session.closed":
                    self._closed.set()
                    return
                elif t == "error":
                    err = getattr(ev, "error", None)
                    log.warning("GPT-Live error: %s %s", getattr(err, "code", ""), getattr(err, "message", ""))
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            log.warning("GPT-Live connection ended: %s", exc)
            self._closed.set()

    async def toggle_listening(self) -> None:
        if self.conn is None:
            return
        if not self.listening:
            self.audio.clear()  # the visitor speaks: the dog stops talking
            self._drain()
            self.listening = True
            await self.conn.session.input_audio.unmute()
            self.stage.status("listening", "push-to-talk on")
        else:
            self.listening = False
            await self.conn.session.input_audio.mute()
            self.stage.status("listening", "off")

    async def _shutdown(self) -> None:
        for t in self._tasks:
            t.cancel()
        await asyncio.gather(*self._tasks, return_exceptions=True)
        self._tasks = []
        if self._mgr is not None:
            try:
                await self._mgr.__aexit__(None, None, None)
            except Exception:
                pass
            self._mgr = None

    async def close(self) -> None:
        self.listening = False
        if self.conn is not None:
            try:
                await self.conn.session.input_audio.mute()
                await self.conn.session.close()
                await asyncio.wait_for(self._closed.wait(), 3)
            except Exception:
                pass
        try:
            self.audio.close()
        except Exception:
            pass
        self.stage.subtitle(None)
        await self._shutdown()


class RealtimePushToTalkWindow(_Window):
    """Fallback when GPT-Live is not available: Realtime with turn detection off."""

    def __init__(self, client, audio, stage, *, model: str, voice: str, instructions: str):
        super().__init__(audio, stage)
        self.client, self.model, self.voice, self.instructions = client, model, voice, instructions
        self._mgr = self.conn = None
        self._sent = 0

    def session_config(self) -> dict:
        return {"type": "realtime", "instructions": self.instructions, "output_modalities": ["audio"],
                "audio": {"input": {"format": {"type": "audio/pcm", "rate": RATE}, "turn_detection": None},
                          "output": {"format": {"type": "audio/pcm", "rate": RATE}, "voice": self.voice}}}

    async def start(self) -> None:
        self._loop = asyncio.get_running_loop()
        self._mgr = self.client.realtime.connect(model=self.model, max_retries=1)
        try:
            self.conn = await self._mgr.__aenter__()
            await self.conn.session.update(session=self.session_config())
        except Exception as exc:
            await self._shutdown()
            raise LiveUnavailable(str(exc) or type(exc).__name__) from exc
        self.audio.start(self._on_mic)

        async def send(b64: str) -> None:
            self._sent += 1
            await self.conn.input_audio_buffer.append(audio=b64)
        self._tasks = [asyncio.ensure_future(self._recv()), asyncio.ensure_future(self._pump(send))]

    async def _recv(self) -> None:
        try:
            while True:
                ev = await self.conn.recv()
                t = getattr(ev, "type", "")
                if t == "response.output_audio.delta":
                    self.audio.play(base64.b64decode(ev.delta))
                elif t == "response.output_audio_transcript.done":
                    line = (ev.transcript or "").strip()
                    if line:
                        self.robot_lines.append(line)
                        self.stage.subtitle(line)
                elif t == "error":
                    err = getattr(ev, "error", None)
                    log.warning("realtime error: %s %s", getattr(err, "code", ""), getattr(err, "message", ""))
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            log.warning("realtime connection ended: %s", exc)

    async def toggle_listening(self) -> None:
        if self.conn is None:
            return
        if not self.listening:
            self.audio.clear()
            self._drain()
            self._sent = 0
            await self.conn.input_audio_buffer.clear()
            self.listening = True
            self.stage.status("listening", "push-to-talk on")
        else:
            self.listening = False
            await asyncio.sleep(0.15)  # let the last chunks go out
            if self._sent:
                await self.conn.input_audio_buffer.commit()
                await self.conn.response.create()
            self.stage.status("listening", "off")

    async def _shutdown(self) -> None:
        for t in self._tasks:
            t.cancel()
        await asyncio.gather(*self._tasks, return_exceptions=True)
        self._tasks = []
        if self._mgr is not None:
            try:
                await self._mgr.__aexit__(None, None, None)
            except Exception:
                pass
            self._mgr = None

    async def close(self) -> None:
        self.listening = False
        try:
            self.audio.close()
        except Exception:
            pass
        self.stage.subtitle(None)
        await self._shutdown()


class ConversationService:
    """Factory used by the director. `enabled` False → the show never opens a window."""

    def __init__(self, *, enabled: bool, client_factory=None, audio_factory=None, stage=None,
                 live_model: str = "gpt-live-1", fallback_model: str = "gpt-realtime-2.1", voice: str = "marin",
                 language: str = "English", story_path: Path | None = None):
        self.enabled = enabled
        self.client_factory = client_factory
        self.audio_factory = audio_factory
        self.stage = stage
        self.live_model, self.fallback_model, self.voice = live_model, fallback_model, voice
        self.language = language
        self.story = ""
        if story_path and Path(story_path).exists():
            from ..talk.persona import load_story

            self.story = load_story(Path(story_path))
        self.live_ok: bool | None = None  # learned at runtime
        self.windows: list = []

    async def open(self, context: dict):
        if not self.enabled:
            return None
        instructions = build_show_instructions(context, language=self.language, story=self.story)
        try:
            client, audio = self.client_factory(), self.audio_factory()
        except Exception as exc:
            log.warning("conversation unavailable (%s); holding on the picture instead", exc)
            return None
        if self.live_ok is not False:
            w = GptLiveWindow(client, audio, self.stage, model=self.live_model, voice=self.voice,
                              instructions=instructions)
            try:
                await w.start()
                self.live_ok = True
                self.windows.append(w)
                return w
            except LiveUnavailable as exc:
                log.warning("GPT-Live (%s) unavailable: %s — using Realtime push-to-talk", self.live_model, exc)
                self.live_ok = False
                audio = self.audio_factory()
        w = RealtimePushToTalkWindow(client, audio, self.stage, model=self.fallback_model, voice=self.voice,
                                     instructions=instructions)
        try:
            await w.start()
            self.windows.append(w)
            return w
        except LiveUnavailable as exc:
            log.warning("conversation unavailable (%s); holding on the picture instead", exc)
            return None
