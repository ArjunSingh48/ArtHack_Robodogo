async def test_director_holds_with_conversation_window(tmp_path):
    """Guided hold: window opens after the narration; NEXT closes it; the model never advances scenes."""
    import random
    from pathlib import Path

    from is_this_us.artworks.repository import YamlArtworkRepository
    from is_this_us.memes.repository import MemeRepository
    from is_this_us.performance.catalog import PerformanceCatalog
    from is_this_us.performance.delivery import PhotoStore
    from is_this_us.performance.director import Cmd, ShowState, StoryDirector
    from is_this_us.performance.lines import Lines
    from is_this_us.performance.script import load_script
    from is_this_us.performance.voice import ShowVoice, Speaker
    from is_this_us.speech.synthesizer import NullSynthesizer

    root = Path(__file__).resolve().parents[1]
    client = FakeClient()
    svc = ConversationService(enabled=True, client_factory=lambda: client, audio_factory=FakeAudio,
                              stage=RecordingStage())
    d = StoryDirector(script=load_script(root / "data/performance"),
                      catalog=PerformanceCatalog(root / "data/performance", YamlArtworkRepository(root / "data/artworks"),
                                                 MemeRepository(root / "data/memes")),
                      lines=Lines.load(root / "data/performance", rng=random.Random(0)),
                      voice=ShowVoice(NullSynthesizer(), NullSynthesizer(), Speaker(enabled=False), time_scale=0),
                      stage=RecordingStage(), store=PhotoStore(tmp_path), conversation=svc, mode="guided",
                      tick_s=0.005, readiness_timeout_s=0.05, try_seconds=0.05)

    def on_state(director, st):
        if st is ShowState.CONVERSATION:
            loop = asyncio.get_running_loop()
            loop.call_later(0.01, lambda: director.command(Cmd.LISTEN))
            loop.call_later(0.02, lambda: director.command(Cmd.LISTEN))
            loop.call_later(0.04, lambda: director.command(Cmd.NEXT))
    d.listeners.append(on_state)
    res = await d.run()
    assert res.final_state is ShowState.FINISHED
    assert len(svc.windows) == 6 and all(w.audio.closed for w in svc.windows)
    starts = [e for e in client.live_conn.log if e[0] == "session.start"]
    assert "The Last Dog" in starts[0][1]["instructions"]
    assert "You can ask me something, if you like." in d.stage.of("subtitle")


