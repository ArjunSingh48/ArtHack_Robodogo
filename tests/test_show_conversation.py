class FakeAudio:
    def __init__(self):
        self.on_mic = None
        self.played = []
        self.cleared = 0
        self.closed = False

    def start(self, on_mic):
        self.on_mic = on_mic

    def play(self, pcm):
        self.played.append(pcm)

    def clear(self):
        self.cleared += 1

    def is_playing(self):
        return False

    def close(self):
        self.closed = True


class Rec:
    def __init__(self, log, name):
        self.log, self.name = log, name

    def __getattr__(self, item):
        async def call(**kw):
            self.log.append((f"{self.name}.{item}", kw))
        return call


class FakeLiveConn:
    def __init__(self, events, fail_start=False):
        self.log = []
        self.events = events
        self.fail_start = fail_start
        self.session = NS(start=self._start, close=self._close, input_audio=Rec(self.log, "input_audio"))

    async def _start(self, session):
        self.log.append(("session.start", session))
        await self.events.put(NS(type="error", error=NS(code="model_not_found", message="no access"))
                              if self.fail_start else NS(type="session.started"))

    async def _close(self):
        self.log.append(("session.close", {}))
        await self.events.put(NS(type="session.closed"))

    async def recv(self):
        return await self.events.get()


class FakeRealtimeConn:
    def __init__(self):
        self.log = []
        self.events = asyncio.Queue()
        self.session = Rec(self.log, "session")
        self.input_audio_buffer = Rec(self.log, "input_audio_buffer")
        self.response = Rec(self.log, "response")

    async def recv(self):
        return await self.events.get()


class Mgr:
    def __init__(self, conn):
        self.conn = conn

    async def __aenter__(self):
        return self.conn

    async def __aexit__(self, *a):
        return False


class FakeClient:
    def __init__(self, live_fail=False):
        self.live_conn = FakeLiveConn(asyncio.Queue(), fail_start=live_fail)
        self.rt_conn = FakeRealtimeConn()
        self.live = NS(connect=lambda **kw: Mgr(self.live_conn))
        self.realtime = NS(connect=lambda **kw: Mgr(self.rt_conn))


CONTEXT = {"chapter": "The Middle Ages", "artworks": [{"title": "Medallion with Varlet with Horn and Hound",
                                                        "artist": "Unknown artist", "date": "ca. 1240–60"}],
           "pose": None}


def test_instructions_carry_facts_and_limits():
    text = build_show_instructions(CONTEXT, story="I was never a puppy.")
    assert "Medallion with Varlet with Horn and Hound" in text and "ca. 1240–60" in text
    assert "biological dogs no longer exist" in text
    assert "cannot move your body by talking" in text and "voice is generated by an AI" in text
    assert "customer-support" in text and "I was never a puppy." in text


def test_gpt_live_session_config_matches_sdk_schema():
    from openai.types.live import SessionStartEvent

    w = GptLiveWindow(None, FakeAudio(), RecordingStage(), model="gpt-live-1", voice="marin", instructions="x")
    ev = SessionStartEvent.model_validate({"type": "session.start", "session": w.session_config()})
    assert ev.session.model == "gpt-live-1" and ev.session.audio.output.voice == "marin"
    assert ev.session.audio.format.rate == 24000
    assert not getattr(ev.session, "delegation", None)  # no tools / no delegation: it controls nothing


def test_realtime_fallback_config_has_no_vad_and_no_tools():
    from openai.types.realtime import SessionUpdateEvent

    w = RealtimePushToTalkWindow(None, FakeAudio(), RecordingStage(), model="gpt-realtime-2.1", voice="marin",
                                 instructions="x")
    cfg = w.session_config()
    SessionUpdateEvent.model_validate({"type": "session.update", "session": cfg})
    assert cfg["audio"]["input"]["turn_detection"] is None and "tools" not in cfg


async def test_push_to_talk_streams_only_while_listening():
    client, audio = FakeClient(), FakeAudio()
    svc = ConversationService(enabled=True, client_factory=lambda: client, audio_factory=lambda: audio,
                              stage=RecordingStage())
    w = await svc.open(CONTEXT)
    assert isinstance(w, GptLiveWindow) and svc.live_ok
    log = client.live_conn.log
    assert ("input_audio.mute", {}) in log  # muted from the start
    audio.on_mic(b"\x01\x00" * 480)
    await asyncio.sleep(0.02)
    assert not [e for e in log if e[0] == "input_audio.append"]
    await w.toggle_listening()
    audio.on_mic(b"\x01\x00" * 480)
    await asyncio.sleep(0.02)
    assert ("input_audio.unmute", {}) in log and [e for e in log if e[0] == "input_audio.append"]
    assert audio.cleared == 1  # the dog stops talking when a visitor speaks
    await w.toggle_listening()
    sent = len([e for e in log if e[0] == "input_audio.append"])
    audio.on_mic(b"\x01\x00" * 480)
    await asyncio.sleep(0.02)
    assert len([e for e in log if e[0] == "input_audio.append"]) == sent
    # the dog's reply is played and subtitled
    await client.live_conn.events.put(NS(type="session.output_audio.delta", delta="AAA="))
    await client.live_conn.events.put(NS(type="session.output_transcript.delta", delta="I am still learning."))
    await asyncio.sleep(0.02)
    assert audio.played and w.robot_lines == ["I am still learning."]
    await w.close()
    assert ("session.close", {}) in log and audio.closed


async def test_falls_back_to_realtime_push_to_talk():
    client = FakeClient(live_fail=True)
    svc = ConversationService(enabled=True, client_factory=lambda: client, audio_factory=FakeAudio,
                              stage=RecordingStage())
    w = await svc.open(CONTEXT)
    assert isinstance(w, RealtimePushToTalkWindow) and svc.live_ok is False
    await w.toggle_listening()
    w.audio.on_mic(b"\x01\x00" * 480)
    await asyncio.sleep(0.02)
    await w.toggle_listening()
    names = [e[0] for e in client.rt_conn.log]
    assert "input_audio_buffer.append" in names
    assert names.index("input_audio_buffer.commit") < names.index("response.create")
    await w.close()
    # remembered: the next window goes straight to the fallback
    w2 = await svc.open(CONTEXT)
    assert isinstance(w2, RealtimePushToTalkWindow)
    await w2.close()


