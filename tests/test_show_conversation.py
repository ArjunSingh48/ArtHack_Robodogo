def test_motion_cues_off_by_default_and_through_guard_when_on():
    import time

    from is_this_us.motion.guard import MotionGuard
    from is_this_us.motion.planner import SafeMotionPlanner
    from is_this_us.robot.mock import MockRobotAdapter

    off = MotionCues(None, None, enabled=True)
    off.request("stand")
    assert not off.enabled and "not performed" in off.log[0]

    robot = MockRobotAdapter(time_scale=0.0)
    robot.connect()
    guard = MotionGuard(robot, hardware_gates_open=False, cooldown_s=0, timeout_s=5)
    cues = MotionCues(guard, SafeMotionPlanner(), enabled=True)
    cues.request("stand")
    for _ in range(100):
        if cues.log:
            break
        time.sleep(0.01)
    assert cues.log and cues.log[0].startswith("stand:")
    cues.request("backflip")
    assert "unknown behavior" in cues.log[-1]
    assert not any("Move" in c or "Flip" in c for c in robot.calls)
    cues.stop("test")
